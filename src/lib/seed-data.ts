import { DatabaseState, GuestProfile } from "@/types/domain";
import { hashCpf, maskCpf, runWangariSalesBoxFunnel } from "./cpf-utils";

function buildEnrichedGuest(
  base: Omit<
    GuestProfile,
    "cpfMasked" | "cpfHash" | "salesBoxFunnelLog" | "marketingCluster" | "waiterAi"
  > & {
    forceCluster?: GuestProfile["marketingCluster"];
  }
): GuestProfile {
  const temp: GuestProfile = {
    ...base,
    cpfMasked: maskCpf(base.cpf),
    cpfHash: hashCpf(base.cpf),
    salesBoxFunnelLog: [],
    marketingCluster: "Novo com potencial",
    waiterAi: {
      wineTier: "MÉDIO (Reserva R$ 220–R$ 420)",
      recommendedWines: [],
      recommendedDishes: [],
      avoidItems: [],
      approachTip: "",
    },
  };

  if (base.enrichmentStatus === "ENRICHED" && base.consents.enrichment.granted) {
    const enriched = runWangariSalesBoxFunnel(temp);
    return {
      ...temp,
      salesBoxAttributes: enriched.salesBoxAttributes,
      salesBoxFunnelLog: enriched.salesBoxFunnelLog,
      marketingCluster: base.forceCluster || enriched.marketingCluster,
      waiterAi: enriched.waiterAi,
    };
  }

  // Caso sem enriquecimento (ex.: bloqueado LGPD ou pendente), gera IA apenas com dados internos do EPOC
  const fallbackAi = runWangariSalesBoxFunnel(temp).waiterAi;
  return {
    ...temp,
    marketingCluster: base.forceCluster || "Baixa aderência de contato",
    waiterAi: fallbackAi,
  };
}

